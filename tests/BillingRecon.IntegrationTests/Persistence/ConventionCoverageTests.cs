using BillingRecon.Domain.Common;
using BillingRecon.Infrastructure.Common.Persistence;
using BillingRecon.IntegrationTests.Support;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;

namespace BillingRecon.IntegrationTests.Persistence;

/// <summary>
/// The conventions of <see cref="BillingReconDbContext"/> are applied in <c>OnModelCreating</c> to the entity types
/// the model has at that moment. An entity type that enters the model later (discovered through a navigation, or
/// added by a derived context after the base call) would get none of them, silently. These tests walk every entity
/// type of the production model and of the test model and check that each one has every convention it qualifies
/// for; the test model is also checked to exercise each convention at least once, so the walk is not vacuous.
/// (The tenant filter and guard have their own walk in <see cref="TenantQueryFilterTests"/>.)
/// </summary>
public sealed class ConventionCoverageTests
{
    private static readonly Dictionary<Type, string> ValueObjectColumns = new()
    {
        [typeof(Money)] = "decimal(18,2)",
        [typeof(UnitPrice)] = "decimal(19,4)",
        [typeof(Quantity)] = "decimal(9,3)",
        [typeof(Percent)] = "decimal(5,2)",
    };

    [Fact]
    public void Every_entity_type_of_the_production_model_has_every_convention_it_qualifies_for()
    {
        using var context = TestContexts.CreateProduction();

        var coverage = AssertConventions(context);

        coverage.TypedIds.ShouldBeGreaterThan(0, "the production model has an Entity<TId> (Tenant)");
        coverage.RowVersions.ShouldBeGreaterThan(0, "the production model has an IHasRowVersion (Tenant)");
        coverage.Enums.ShouldBeGreaterThan(0, "the production model has an enum column (Tenant.Status)");
        coverage.ValueObjects.ShouldBeGreaterThan(0, "the production model has a Money column (Tenant.PostingApprovalThreshold)");
    }

    [Fact]
    public void Every_entity_type_of_the_test_model_has_every_convention_it_qualifies_for()
    {
        using var context = TestContexts.Create(FixedIdentity.Random());

        var coverage = AssertConventions(context);

        // Widget, LogLine and Setting between them qualify for every convention; a probe entity that stops doing so
        // would make the walk prove less than it claims.
        coverage.TypedIds.ShouldBeGreaterThan(0);
        coverage.AggregateRoots.ShouldBeGreaterThan(0);
        coverage.RowVersions.ShouldBeGreaterThan(0);
        coverage.CreationAudited.ShouldBeGreaterThan(0);
        coverage.Enums.ShouldBeGreaterThan(0);
        coverage.Instants.ShouldBeGreaterThan(0);
        coverage.BusinessDates.ShouldBeGreaterThan(0);
    }

    private static Coverage AssertConventions(DbContext context)
    {
        var coverage = new Coverage();

        // The design-time model: the runtime model drops what queries and saves never need, the check constraints
        // among it.
        foreach (var entityType in context.GetService<IDesignTimeModel>().Model.GetEntityTypes())
        {
            var clrType = entityType.ClrType;
            var name = clrType.Name;

            if (FindGenericBase(clrType, typeof(Entity<>)) is { } entityBase)
            {
                var idType = entityBase.GetGenericArguments()[0];
                var id = entityType.FindProperty(nameof(Entity<TenantId>.Id)).ShouldNotBeNull($"{name} has no Id property");
                var factory = id.GetValueGeneratorFactory().ShouldNotBeNull($"{name}.Id has no value generator");
                factory(id, entityType).ShouldBeOfType(typeof(TypedIdValueGenerator<>).MakeGenericType(idType), $"{name}.Id is not generated as a typed id");
                coverage.TypedIds++;
            }

            if (FindGenericBase(clrType, typeof(AggregateRoot<>)) is not null)
            {
                entityType.FindProperty(nameof(AggregateRoot<TenantId>.DomainEvents)).ShouldBeNull($"{name}.DomainEvents is mapped as a column");
                entityType.FindNavigation(nameof(AggregateRoot<TenantId>.DomainEvents)).ShouldBeNull($"{name}.DomainEvents is mapped as a navigation");
                coverage.AggregateRoots++;
            }

            if (typeof(IHasRowVersion).IsAssignableFrom(clrType))
            {
                var rowVersion = entityType.FindProperty(nameof(IHasRowVersion.RowVersion)).ShouldNotBeNull($"{name} has no RowVersion property");
                rowVersion.IsConcurrencyToken.ShouldBeTrue($"{name}.RowVersion is not a concurrency token");
                rowVersion.ValueGenerated.ShouldBe(ValueGenerated.OnAddOrUpdate, $"{name}.RowVersion is not generated by the database");
                rowVersion.GetColumnType().ShouldBe("rowversion", $"{name}.RowVersion is not a rowversion column");
                coverage.RowVersions++;
            }

            if (typeof(ICreationAudited).IsAssignableFrom(clrType))
            {
                foreach (var column in new[] { nameof(ICreationAudited.CreatedAtUtc), nameof(ICreationAudited.CreatedByUserId) })
                {
                    entityType.FindProperty(column).ShouldNotBeNull($"{name} has no {column} property")
                        .GetAfterSaveBehavior().ShouldBe(PropertySaveBehavior.Ignore, $"{name}.{column} could be part of an UPDATE");
                }

                coverage.CreationAudited++;
            }

            var table = entityType.GetTableName().ShouldNotBeNull($"{name} is not mapped to a table");
            var constraints = entityType.GetCheckConstraints().ToDictionary(constraint => constraint.Name!, constraint => constraint.Sql, StringComparer.Ordinal);

            foreach (var property in entityType.GetProperties())
            {
                var propertyType = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;
                var columnName = property.GetColumnName();

                if (propertyType.IsEnum)
                {
                    var names = string.Join(", ", Enum.GetNames(propertyType).Select(member => $"'{member}'"));
                    property.GetColumnType().ShouldStartWith("varchar(", customMessage: $"{name}.{property.Name} is not stored by name");
                    constraints.ShouldContainKeyAndValue($"CK_{table}_{columnName}", $"[{columnName}] IN ({names})");
                    coverage.Enums++;
                }

                if (propertyType == typeof(DateTimeOffset))
                {
                    property.GetColumnType().ShouldBe("datetimeoffset(3)", $"{name}.{property.Name} is not a datetimeoffset(3)");
                    coverage.Instants++;
                }

                if (propertyType == typeof(DateOnly))
                {
                    property.GetColumnType().ShouldBe("date", $"{name}.{property.Name} is not a date");
                    coverage.BusinessDates++;
                }

                if (typeof(ITypedId).IsAssignableFrom(propertyType))
                {
                    property.GetColumnType().ShouldBe("uniqueidentifier", $"{name}.{property.Name} is not a uniqueidentifier");
                }

                // The value objects of ADR 0004: each has the column of docs/database.md section 1, by convention.
                if (ValueObjectColumns.TryGetValue(propertyType, out var valueObjectColumn))
                {
                    property.GetColumnType().ShouldBe(valueObjectColumn, $"{name}.{property.Name} has not the column of its value object");
                    coverage.ValueObjects++;
                }
            }
        }

        return coverage;
    }

    private static Type? FindGenericBase(Type type, Type genericBase)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.IsGenericType && current.GetGenericTypeDefinition() == genericBase)
            {
                return current;
            }
        }

        return null;
    }

    private sealed class Coverage
    {
        public int TypedIds { get; set; }

        public int AggregateRoots { get; set; }

        public int RowVersions { get; set; }

        public int CreationAudited { get; set; }

        public int Enums { get; set; }

        public int Instants { get; set; }

        public int BusinessDates { get; set; }

        public int ValueObjects { get; set; }
    }
}
